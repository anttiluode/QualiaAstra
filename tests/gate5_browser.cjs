/* Gate 5 browser: no-copy provenance, posterior updates, causal cuts, offline/mobile. */
const assert=require("node:assert/strict");
const path=require("path"),{chromium}=require("playwright");
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1330,height:1000}});
const errors=[];page.on("pageerror",err=>errors.push(err.message));
await page.goto("file://"+path.resolve("gate5.html"));
assert.match(await page.title(),/Gate 5/);
await page.locator("#signA").selectOption("1");
await page.locator("#signZ").selectOption("1");
await page.locator("#reliability").fill(".95");
await page.locator("#provenance").selectOption("replay");
const rep=parseFloat(await page.locator("#beliefC").textContent());
await page.locator("#provenance").selectOption("actual");
const actual=parseFloat(await page.locator("#beliefC").textContent());
const blind=parseFloat(await page.locator("#blindC").textContent());
assert(actual>rep,"Real B reading must update C");
assert(blind>rep&&blind<actual,"No-provenance optimal mixture interpolates");
await page.locator("#provenance").selectOption("replay");
const held=parseFloat(await page.locator("#beliefB").textContent());
const naive1=parseFloat(await page.locator("#naiveConf").textContent());
await page.locator("#copies").fill("8");
const held8=parseFloat(await page.locator("#beliefB").textContent());
const naive8=parseFloat(await page.locator("#naiveConf").textContent());
assert.equal(held8,held,"Repeated replays must not alter aware internal state");
assert(naive8>naive1,"Naive model becomes overconfident from duplicates");
await page.locator("#signZ").selectOption("-1");
await page.locator("#provenance").selectOption("actual");
const negative=parseFloat(await page.locator("#beliefC").textContent());
assert(negative<0,"Reliable negative observation must reverse C");
const bBefore=parseFloat(await page.locator("#beliefB").textContent());
await page.locator("#cutBC").check();
assert(Math.abs(parseFloat(await page.locator("#beliefC").textContent()))===0,"B→C cut forces zero C prediction");
assert.equal(parseFloat(await page.locator("#beliefB").textContent()),bBefore,"Causal cut keeps B state");
await page.locator("#truth").check();
assert.match(await page.locator("#waveError").textContent(),/Withheld C waveform squared error/);
await page.locator("#cutBC").uncheck();
await page.locator("#benchmark").click();
const results=await page.locator("#results").textContent();
assert.match(results,/Optimal receiver without origin/);
assert.match(results,/Incorrectly reassigned provenance/);
assert.match(results,/the no-tag Bayesian mixture/);
await page.screenshot({path:"/tmp/qualia-gate5-desktop.png",fullPage:true});
await page.setViewportSize({width:390,height:830});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,"No mobile overflow");
await page.screenshot({path:"/tmp/qualia-gate5-mobile.png",fullPage:true});
await page.locator("#next").click();
await page.locator("#retrain").click();
assert.match(await page.locator("#fit").textContent(),/Calibration seed 17014/);
assert.deepEqual(errors,[],"Gate 5 browser JavaScript errors");
console.log("Gate 5 browser checks pass: provenance, false confidence, reversals, cut, hidden-wave evaluation, benchmark, mobile, retrain");
await browser.close();
})().catch(err=>{console.error(err);process.exit(1);});
