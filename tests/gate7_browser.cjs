/* Gate 7: offline end-to-end browser and causal handoff checks */
const assert=require("node:assert/strict");
const path=require("path"),{chromium}=require("playwright");
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1370,height:990}});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
await page.goto("file://"+path.resolve("gate7.html"));
assert.match(await page.title(),/Gate 7/);
assert.match(await page.locator("#training").textContent(),/512 observed episodes/);
await page.locator("#policy").selectOption("residual");
await page.locator("#A").selectOption("1");
await page.locator("#z").selectOption("1");
await page.locator("#p").fill(".95");
await page.locator("#origin").selectOption("replay");
const direct=parseFloat(await page.locator("#directWeight").textContent());
assert(Math.abs(direct)<.15,"Conditional residual should screen direct A");
const held=parseFloat(await page.locator("#beliefB").textContent());
const relayC=parseFloat(await page.locator("#beliefC").textContent());
assert(held>.25&&relayC>.05,"Imagined B must give a C prediction with no external B");
await page.locator("#policy").selectOption("noRelay");
const missing=parseFloat(await page.locator("#beliefC").textContent());
assert(relayC>missing+.15,"Removing imagined B suppresses C on self-replay");
await page.locator("#policy").selectOption("similarity");
const hebbA=parseFloat(await page.locator("#directWeight").textContent());
assert(hebbA>.35,"Independent similarity retains direct A shortcut");
await page.locator("#policy").selectOption("residual");
await page.locator("#origin").selectOption("actual");
const realC=parseFloat(await page.locator("#beliefC").textContent());
assert(realC>relayC,"True sensor evidence should revise C above imagined replay");
const beforeSwap=parseFloat(await page.locator("#physicalProb").textContent());
await page.locator("#swap").check();
const afterSwap=parseFloat(await page.locator("#physicalProb").textContent());
assert(afterSwap<beforeSwap,"Source-specific physical waveform swap must reverse decoding");
await page.locator("#swap").uncheck();
await page.locator("#z").selectOption("-1");
const flipped=parseFloat(await page.locator("#beliefC").textContent());
assert(flipped<0,"Contradictory B sensor reverses residual C");
await page.locator("#policy").selectOption("similarity");
const similarityFlipped=parseFloat(await page.locator("#beliefC").textContent());
assert(similarityFlipped>flipped,"Spurious direct A shortcut opposes genuine contradictory B");
await page.locator("#policy").selectOption("residual");
const Bbefore=parseFloat(await page.locator("#beliefB").textContent());
const Cbefore=parseFloat(await page.locator("#beliefC").textContent());
const W=parseFloat(await page.locator("#relayWeight").textContent());
await page.locator("#cutBC").check();
const Bafter=parseFloat(await page.locator("#beliefB").textContent());
const Cafter=parseFloat(await page.locator("#beliefC").textContent());
assert.equal(Bafter,Bbefore,"Cut must preserve held B");
assert(Math.abs((Cbefore-Cafter)-W*Bbefore)<.003,"Cut removes only B→C contribution (rounded UI)");
await page.locator("#truth").check();
assert.match(await page.locator("#truthNote").textContent(),/true C wave/);
await page.locator("#benchmark").click();
assert.match(await page.locator("#results").textContent(),/Joint OLS/);
assert.match(await page.locator("#results").textContent(),/When only an imagined B is present/);
await page.screenshot({path:"/tmp/qualia-gate7-desktop.png",fullPage:true});
await page.setViewportSize({width:390,height:830});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,"Gate7 mobile overflow");
await page.screenshot({path:"/tmp/qualia-gate7-mobile.png",fullPage:true});
await page.locator("#newWorld").click();
await page.locator("#retrain").click();
assert.match(await page.locator("#training").textContent(),/Body 17020/);
assert.deepEqual(errors,[],"Gate7 unexpected JS page errors");
console.log("Gate 7 browser: screened shortcut, imagined relay, real update, swap, cut, negative B, held state and mobile passed");
await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
