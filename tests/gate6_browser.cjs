/* Gate 6 browser: physical wave source, no tag at inference, causal controls, mobile. */
const assert=require("node:assert/strict");
const path=require("path"),{chromium}=require("playwright");
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1330,height:960}});
const exceptions=[];page.on("pageerror",error=>exceptions.push(error.message));
await page.goto("file://"+path.resolve("gate6.html"));
assert.match(await page.title(),/Gate 6/);
assert.match(await page.locator("#calInfo").textContent(),/320 known-source calibration/);
await page.locator("#A").selectOption("1");
await page.locator("#z").selectOption("1");
await page.locator("#p").fill(".95");
await page.locator("#mode").selectOption("cable");
await page.locator("#origin").selectOption("actual");
const pActual=parseFloat(await page.locator("#realProb").textContent()),cActual=parseFloat(await page.locator("#beliefC").textContent());
await page.locator("#origin").selectOption("replay");
const pReplay=parseFloat(await page.locator("#realProb").textContent()),cReplay=parseFloat(await page.locator("#beliefC").textContent());
assert(pActual>pReplay+.30,"Fast real wave must differ from replay in same signed report");
assert(cActual>cReplay,"Physical origin must change the predicted C");
await page.locator("#mode").selectOption("equalized");
await page.locator("#origin").selectOption("actual");
const nullActual=parseFloat(await page.locator("#realProb").textContent());
await page.locator("#origin").selectOption("replay");
const nullReplay=parseFloat(await page.locator("#realProb").textContent());
assert(Math.abs(nullActual-nullReplay)<.0001,"Equalized waves must erase all physical source evidence");
await page.locator("#mode").selectOption("cable");
await page.locator("#origin").selectOption("actual");
const normalP=parseFloat(await page.locator("#realProb").textContent());
await page.locator("#swapped").check();
const swappedP=parseFloat(await page.locator("#realProb").textContent());
assert(swappedP<normalP,"Swapping route signatures must reverse source inference");
await page.locator("#swapped").uncheck();
const beforeB=parseFloat(await page.locator("#beliefB").textContent());
await page.locator("#cut").check();
assert.equal(parseFloat(await page.locator("#beliefC").textContent()),0,"Cut B→C zeroes C");
assert.equal(parseFloat(await page.locator("#beliefB").textContent()),beforeB,"Cut must not erase B");
await page.locator("#cut").uncheck();
await page.locator("#truth").check();
assert.match(await page.locator("#cError").textContent(),/True C waveform/);
await page.locator("#benchmark").click();
const rows=await page.locator("#results").textContent();
assert.match(rows,/Optimal no-wave baseline/);
assert.match(rows,/Identical waveforms/);
assert.match(rows,/Among ambiguous z=A reports only/);
await page.screenshot({path:"/tmp/qualia-gate6-desktop.png",fullPage:true});
await page.setViewportSize({width:390,height:830});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,"Mobile horizontal overflow");
await page.screenshot({path:"/tmp/qualia-gate6-mobile.png",fullPage:true});
await page.locator("#resample").click();
await page.locator("#new").click();
await page.locator("#retrain").click();
assert.match(await page.locator("#calInfo").textContent(),/Body 17020/);
assert.deepEqual(exceptions,[],"Gate 6 page JavaScript exceptions");
console.log("Gate 6 offline browser passed: physical source discrimination, equalized null, swap, cut, hidden C, benchmark, mobile");
await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
