/* Gate 3 offline/browser controls with Playwright */
const {chromium}=require("playwright"),assert=require("node:assert/strict"),path=require("path");
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1400,height:1100}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("file://"+path.resolve("gate3.html"));
 assert(Math.abs(Number(await page.locator("#beliefC").textContent()))<.001,"No clue should preserve global ambiguity");
 await page.locator("#reveal").click();
 const a=Number(await page.locator("#beliefA").textContent());
 const b=Number(await page.locator("#beliefB").textContent());
 const c=Number(await page.locator("#beliefC").textContent());
 assert(Math.abs(a)>.01&&Math.abs(b)>.01&&Math.abs(c)>.01,"Learned chain must respond to A clue");
 await page.locator("#mode").selectOption("cut");
 assert(Math.abs(Number(await page.locator("#beliefB").textContent()))<.001);
 assert(Math.abs(Number(await page.locator("#beliefC").textContent()))<.001);
 await page.locator("#mode").selectOption("cutBC");
 assert(Math.abs(Number(await page.locator("#beliefB").textContent())-b)<.02);
 assert(Math.abs(Number(await page.locator("#beliefC").textContent()))<.001);
 await page.locator("#mode").selectOption("reverse");
 assert(Math.abs(Number(await page.locator("#beliefA").textContent())-a)<.02);
 assert(Math.abs(Number(await page.locator("#beliefB").textContent())+b)<.02);
 assert(Math.abs(Number(await page.locator("#beliefC").textContent())+c)<.02);
 await page.locator("#mode").selectOption("learned");
 await page.locator("#truth").check();
 assert.match(await page.locator("#error").textContent(),/Withheld-wave squared error/);
 await page.locator("#benchmark").click();
 assert.match(await page.locator("#results").textContent(),/Future training events mispaired/);
 assert.match(await page.locator("#results").textContent(),/supervised reference/);
 await page.screenshot({path:"/tmp/qualia-gate3-desktop.png",fullPage:true});
 await page.setViewportSize({width:390,height:850});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,"No mobile horizontal overflow");
 await page.screenshot({path:"/tmp/qualia-gate3-mobile.png",fullPage:true});
 await page.locator("#new").click();
 assert(Math.abs(Number(await page.locator("#beliefC").textContent()))<.001);
 await page.locator("#recalibrate").click();
 assert.match(await page.locator("#calibration").textContent(),/unlabelled episodes/);
 assert.deepEqual(errors,[],"No browser exceptions");
 console.log("Gate 3 browser checks: offline, ambiguity, cut, B→C cut, reverse, truth, benchmark, mobile, reset, retrain all pass");
 await browser.close();
})().catch(err=>{console.error(err);process.exit(1);});
