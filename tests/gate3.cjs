/* Gate 3 mechanism and no-label-inference checks */
const assert=require("node:assert/strict");
require("../gate2_engine.js");
require("../gate3_engine.js");
const G=globalThis.Gate3,E2=globalThis.Gate2;
assert(G);
const m=G.train(1401,256),m2=G.train(1401,256);
assert.deepEqual(m,m2,"Seeded training must reproduce");
const observed=G.observedCases(1401,256);
assert(observed.every(x=>!Object.prototype.hasOwnProperty.call(x,"signs")&&!Object.prototype.hasOwnProperty.call(x,"relation")),"Teacher labels must never reach Gate 3 training");
const poison=observed.map(x=>({...x,signs:[100,200,300],relation:[-7,-9]}));
assert.deepEqual(G.trainFromObserved(poison,1401),G.trainFromObserved(observed,1401),"Hidden sign fields must be irrelevant");
const raw=E2.newCase(E2.rng(29002)).raw;
const missing=G.infer(m,raw,null);
assert(missing.means.every(x=>Math.abs(x)===0),"Global sign must remain unresolved without clue");
const normal=G.infer(m,raw,1.3);
const cut=G.infer(m,raw,1.3,"cut"),bc=G.infer(m,raw,1.3,"cutBC"),rev=G.infer(m,raw,1.3,"reverse");
assert(Math.abs(cut.means[1])===0&&Math.abs(cut.means[2])===0);
assert(Math.abs(bc.means[2])===0&&bc.means[1]===normal.means[1]);
assert(rev.means[0]===normal.means[0]);
assert(Math.abs(rev.means[1]+normal.means[1])<1e-12);
assert(Math.abs(rev.means[2]+normal.means[2])<1e-12);
const badFuture=observed.map((x,i)=>({...x,future:[Array(G.N).fill(i+1),Array(G.N).fill(-(i+1))]}));
assert.deepEqual(G.infer(m,raw,1.3),G.infer(m,raw,1.3),"Inference determinism");
const test=G.benchmark(m,20261116,512);
const e=test.relativeMSE;
assert(e.learned<.80,"Label-free development model should predict held-out waveforms");
assert(Math.abs(e.cut-1)<1e-12);
assert(e.cutBC>e.learned);
assert(e.shuffled>e.learned+.20);
assert(e.unpaired>e.learned+.20);
assert(e.learned<e.supervised+.10);
console.log("Gate 3 development mechanisms:",JSON.stringify(test));
