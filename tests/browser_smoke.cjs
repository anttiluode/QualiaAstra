const {chromium}=require('playwright');
const assert=require('assert'),path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1400,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve('index.html'));
 assert.equal(await page.locator('#beliefC').textContent(),'P(+) 50.0%');
 assert.equal(await page.locator('#clue').inputValue(),'0');
 await page.locator('#reveal').click();
 await page.locator('#clue').evaluate(e=>{e.value=1;e.dispatchEvent(new Event('input'));});
 const normal=await page.locator('#beliefC').textContent(),entropy=await page.locator('#entropy').textContent();
 assert.notEqual(normal,'P(+) 50.0%');
 await page.locator('#mode').selectOption('cut');
 assert.equal(await page.locator('#beliefC').textContent(),'P(+) 50.0%');
 assert.equal(await page.locator('#entropy').textContent(),entropy);
 await page.locator('#mode').selectOption('reverse');
 assert.notEqual(await page.locator('#beliefC').textContent(),normal);
 assert.equal(await page.locator('#entropy').textContent(),entropy);
 await page.locator('#mode').selectOption('shared');
 await page.locator('#remove').check();
 assert.equal(await page.locator('#beliefC').textContent(),normal);
 await page.locator('#remove').uncheck();
 await page.screenshot({path:'/tmp/qualia-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Mobile horizontal overflow');
 await page.screenshot({path:'/tmp/qualia-mobile.png',fullPage:true});
 await page.locator('#new').click();
 assert.equal(await page.locator('#clue').inputValue(),'0');
 assert.equal(await page.locator('#beliefC').textContent(),'P(+) 50.0%');
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: offline load, reveal, cut, reverse, output-only removal, reference posterior, mobile width, reset; no page errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
